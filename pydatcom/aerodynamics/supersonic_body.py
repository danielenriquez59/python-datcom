def calculate_sypbod(data: Mapping[str, object]) -> Dict[str, object]:
    """Translate SYPBOD: supersonic body-alone aerodynamics.

    Args:
        data: By name: ``alpha`` (``FLC(23..)``), ``mach``, ``rl``
            (``FLC(I+42)``), ``transn`` (the transonic call: Mach 1.4 and
            beta 0.98, no curves), ``body`` (``/BODYI/``: ``x``, ``s``,
            ``perim``, ``r``, ``bnose``, ``btail``, ``rln``, ``rla``,
            ``ellip``), ``xcg``, ``sref``, ``cbarr``, ``rough``, and
            ``stale``: ``rach`` (the saved Mach number FIG26 reads without
            roughness), the ``SBD`` words ``cda`` (119) and ``thetat``
            (135).

    Returns:
        ``sbd`` (the words set, by index), the ``BD`` curves ``req``,
        ``cnpot``, ``cnvis``, ``cmpot``, ``cmvis`` and the ``BODY`` curves
        ``cd``, ``cl``, ``cm``, ``cn``, ``ca``, and ``ellip`` as left.

    Notes:
        Kept as executed: with no afterbody wave drag the routine zeroes
        ``CDAB`` but not ``CDA``, which still enters ``CD0``; without
        roughness FIG26 is read at the Mach number the previous call left.
    """
    b = data['body']
    x = [float(v) for v in b['x']]
    r = [float(v) for v in b['r']]
    s = [float(v) for v in b['s']]
    perim = [float(v) for v in b['perim']]
    nx = len(x)
    bnose, btail = float(b['bnose']), float(b['btail'])
    rln, rla = float(b['rln']), float(b['rla'])
    ellip = float(b['ellip'])
    st = dict(data.get('stale', {}))
    rnfs = float(data['rl'])
    sr, crbar = float(data['sref']), float(data['cbarr'])
    xcg, ruff = float(data['xcg']), float(data['rough'])
    transn = bool(data['transn'])
    alpha = [float(v) for v in data['alpha']]
    na = len(alpha)
    sbd: Dict[int, float] = {}
    rlbp = rln + rla
    rlb = x[-1]
    rlbt = rlb - rlbp
    tail = btail in (1., 2.)
    if not tail:
        rlbt = 0.0
    nostal = tail and rla == 0.0
    loop = 2
    if tail and rla != 0.0:
        loop = 3
    if not tail and rla == 0.0:
        loop = 1

    def dia_at(station):
        return _ix(1, x, [station], [nx], r, nx)

    dn = d1 = d2 = 0.0
    for diameter_pass in range(1, loop + 1):
        if diameter_pass == 1:
            dn = dia_at(rln) * 2.
            d1 = d2 = dn
        elif diameter_pass == 2:
            dia = dia_at(rlb if nostal else rlbp)
            if nostal:
                d1, d2 = dn, dia * 2.
            elif loop == 2:
                d1 = dia * 2.
                d2 = d1
            else:
                d1 = dia * 2.
        else:
            d2 = dia_at(rlb) * 2.
    if transn:
        mach, beta = 1.4, 0.98
    else:
        mach = float(data['mach'])
        beta = math.sqrt(mach**2 - 1.)
    dcyl = (dn + d1) / 2.0
    if d2 == 0.0:
        d2 = 0.3 * dcyl
    fa, fn = rla / dcyl, rln / dn
    var = [beta / fn, fa / fn]
    if bnose == 1.:
        cnaoc = _ix(2, _T4221B, var, [10, 8], _D4221B, 10, lx1l=1,
                    lx1u=1, lx2u=2)
    else:
        cnaoc = _ix(2, _T4221A, var, [11, 8], _D4221A, 11, lx1l=1,
                    lx1u=2, lx2u=2)
    thetat = float(st.get('thetat', 0.0))
    thetab = thetaf = None
    delcna = 0.0
    if tail:
        if d2 / d1 > 1.:
            dccos = _ix(1, _T4222B, [d2 / d1], [6], _D4222B, 6, lx1u=2)
            thetaf = math.atan(.5 * (d2 - d1) / rlbt)
            sbd[102] = sbd[16] = thetaf
            thetat = thetaf
            delcna = dccos * math.cos(thetaf)**2
        else:
            thetab = math.atan(.5 * (d1 - d2) / rlbt)
            thetat = thetab
            fb = rlbt / d1
            sbd[9], sbd[14] = fb, thetab
            dcd1d2 = _ix(1, _T4222A, [fb / beta], [8], _D4222A, 8)
            delcna = dcd1d2 * (1. - (d2 / d1)**2)
    cna = (cnaoc + delcna) * PI * d1**2 / (4. * RAD * sr)
    sbd.update({1: rlbp, 2: rlb, 3: rlbt, 4: dn, 5: d1, 6: d2, 7: beta,
                8: fa, 10: fn, 15: delcna, 17: cnaoc, 18: cna, 135: thetat})
    out: Dict[str, object] = {}
    cn = [0.0] * na
    cflow = [0.0] * na
    alschr = [a / RAD for a in alpha]
    cnocns = cnocnn = 1.0
    sp = 0.0
    if not transn:
        sb = PI * d2**2 / 4.
        a1 = sb
        if ellip <= UNUSED:
            ellip = 1.0
        if ellip == 1.0:
            a1 = cna * sr * RAD / 2.0
        sp = 2. * float(trapz(r, x)[0])
        sbd.update({19: sb, 20: sp})
        mc, cdc = [], []
        cnpot, cnvis = [], []
        for angle_index in range(na):
            mc.append(mach * abs(math.sin(alschr[angle_index])))
            cdc.append(_ix(1, _T4217B, [mc[angle_index]], [18], _D4217B, 18))
            cflow[angle_index] = (cdc[angle_index] * sp *
                                  math.sin(alschr[angle_index])**2 / sr)
            if alschr[angle_index] < 0.0:
                cflow[angle_index] = -cflow[angle_index]
            aob = 1. / ellip if ellip < 1. else ellip
            cnocns = aob if ellip < 1. else 1. / aob
            cnocnn = 1.0
            if ellip < 1.:
                cnocnn = 1.5 * math.sqrt(aob) * (
                    -1. / aob**2 / (1. - 1. / aob**2)**1.5 *
                    math.log(aob * (1. + math.sqrt(1. - 1. / aob**2))) +
                    1. / (1. - 1. / aob**2))
            if ellip > 1.:
                cnocnn = 1.5 * math.sqrt(1. / aob) * (
                    aob**2 / (aob**2 - 1.)**1.5 *
                    math.atan(math.sqrt(aob**2 - 1.)) - 1. / (aob**2 - 1.))
            cnpot.append(math.sin(2. * alschr[angle_index]) *
                         math.cos(alschr[angle_index] / 2.) * a1 * cnocns / sr)
            cnvis.append(cflow[angle_index] * cnocnn)
            cn[angle_index] = cnpot[angle_index] + cnvis[angle_index]
        for angle_index in range(na):
            sbd[21 + angle_index], sbd[41 + angle_index] = (alschr[angle_index],
                                                            mc[angle_index])
            sbd[61 + angle_index], sbd[81 + angle_index] = (cdc[angle_index],
                                                            cflow[angle_index])
        out.update({'cnpot': cnpot, 'cnvis': cnvis})
    var = [beta / fn, fa / fn]
    if bnose == 1.:
        if var[0] > 1.:
            xcplb = _ix(2, _T4218B, [1. / var[0], var[1]], [6, 7], _DR218B,
                        7, lx1l=1, lx2u=2)
        else:
            xcplb = _ix(2, _T4218B, var, [6, 7], _DL218B, 7, lx1l=1,
                        lx2u=2)
    else:
        if var[0] > 1.:
            xcplb = _ix(2, _T4218A, [1. / var[0], var[1]], [6, 9], _DR218A,
                        9, lx1l=1, lx2u=2)
        else:
            xcplb = _ix(2, _T4218A, var, [6, 9], _DL218A, 9, lx1l=1,
                        lx2u=2)
    cmaoc = (xcg / rlbp - xcplb) * cnaoc
    delcma = 0.0
    if tail:
        if d2 / d1 < 1.0:
            xcpblb = _ix(2, _T42119, [beta * math.tan(thetab), d2 / d1],
                         [11, 7], _D42119, 11, lx1u=2)
            sbd[101] = xcpblb
            delcma = delcna * (2. * xcg / rlbp - 1.0 - xcpblb * rlbt / rlbp)
        else:
            cmap = _ix(2, _T4220A, [thetaf * RAD, d1 / d2], [18, 11],
                       _D4220A, 18)
            sbd[103] = cmap
            delcma = cmap * (d2**3 / (d1**2 * rlbp)) + \
                ((xcg - rlbp) / rlbp) * delcna
    cma = (cmaoc + delcma) * PI * d1**2 * rlbp / (4. * sr * crbar * RAD)
    sbd.update({11: xcplb, 12: cmaoc, 13: delcma, 110: cma})
    cm = [0.0] * na
    if not transn:
        req = [math.sqrt(v / PI) for v in s]
        rx = [a * b for a, b in zip(req, x)]
        xc = 2. * float(trapz(rx, x)[0]) / sp
        vb = float(trapz(req, x, -1)[0])
        arg1 = vb / (sr * crbar) - (rlb - xcg) * sbd[19] / (sr * crbar)
        if ellip == 1.0:
            arg1 = cma * RAD / 2.0
        cmpot, cmvis = [], []
        for angle_index in range(na):
            cmpot.append(math.sin(2. * alschr[angle_index]) *
                         math.cos(alschr[angle_index] / 2.) * arg1 * cnocns)
            cmvis.append(cflow[angle_index] / crbar * (xcg - xc) * cnocnn)
            cm[angle_index] = cmvis[angle_index] + cmpot[angle_index]
        sbd.update({105: xc, 106: vb})
        out.update({'req': req, 'cmpot': cmpot, 'cmvis': cmvis})
    var2 = 2. * rln / (beta * dn)
    if bnose == 1.:
        cdn2p = _ix(2, _T4228, [0.0, var2], [10, 10], _D4228, 10, lx2u=2)
    else:
        cdn2p = _ix(2, _T4227, [0.0, var2], [12, 10], _D4227, 12, lx2l=2,
                    lx2u=2)
    cdn2 = cdn2p * PI * dn**4 / (16. * sr * rln**2)
    ss = 0.0
    for station in range(nx - 1):
        ss += ((perim[station + 1] + perim[station]) *
               (x[station + 1] - x[station]) / 2.)
    rnb = rlb * rnfs
    rach = float(st.get('rach', 0.0))
    rlcoff = st.get('rlcoff')
    if ruff != 0.0:
        rach = min(mach, 3.0)
        cept = tbfunx(_X27M, _X27I, rach, 0, 0)[0]
        rlcoff = (12. * rlb / ruff)**1.0482 * 10.0**cept
        if rlcoff < rnb:
            rnb = rlcoff
        sbd[113] = rlcoff
    cf = fig26(rnb, rach)
    cdf = cf * ss / sr
    sbd.update({107: cdn2p, 108: cdn2, 111: ss, 112: rnb, 114: cf,
                115: cdf})
    cdanc = 0.0
    pair = None
    if rla != 0.0:
        pair = (d1, dn, rla)
    elif rlbt != 0.0:
        pair = (d1, d2, rlbt)
    if pair is not None:
        da, db, arg = pair
        cdanf = _ix(2, _T44A, [(db / da)**2, rln / arg], [6, 3], _D44A, 6)
        cdanc = cdanf * PI * db**4 / (16. * sr * arg**2)
        sbd[116] = cdanf
    sbd[117] = cdanc
    cda = float(st.get('cda', 0.0))
    if rla != 0.0 and tail:
        dd, aa = (d2, d1) if d2 / d1 > 1. else (d1, d2)
        v = [(aa / dd)**2, 2. * rlbt / (beta * dd)]
        if btail == 1.:
            cdab = _ix(2, _T4228, v, [10, 10], _D4228, 10, lx2u=2)
        else:
            cdab = _ix(2, _T4227, v, [12, 10], _D4227, 12, lx2l=2, lx2u=2)
        cda = cdab * PI * dd**4 / (16. * sr * rlbt**2)
    else:
        cdab = 0.0
    sbd.update({118: cdab, 119: cda})
    dmax = 2. * max(r)
    if not (rlbt != 0.0 or d2 / d1 < 1.0):
        cdd = _ix(1, _T4360, [mach], [13], _D4360, 13)
    else:
        table = _D4355 if btail == 1. else _D4350
        cpb = _ix(3, _T5055, [mach, d2 / dmax, rlbt / d1], [11, 5, 5],
                  table, 11, lx3l=2, lx3u=2)
        cdd = -cpb * (d2 / dmax)**2
        sbd[122] = cpb
    cdb = cdd * PI * dmax**2 / (4. * sr)
    cdo = cdf + cdn2 + cda + cdanc + cdb
    sbd.update({120: dmax, 121: cdd, 123: cdb, 124: cdo})
    out.update({'sbd': sbd, 'ellip': ellip, 'rach': rach,
                'method': 'legacy_sypbod'})
    if transn:
        return out
    ca, cl, cd = [], [], []
    for angle_index in range(na):
        cosa = math.cos(alpha[angle_index] / RAD)
        sina = math.sin(alpha[angle_index] / RAD)
        ca.append(cdo * cosa**2)
        cl.append(cn[angle_index] * cosa - ca[angle_index] * sina)
        cd.append(ca[angle_index] * cosa + cn[angle_index] * sina)
    out.update({'cn': cn, 'cm': cm, 'ca': ca, 'cl': cl, 'cd': cd})
    return out
