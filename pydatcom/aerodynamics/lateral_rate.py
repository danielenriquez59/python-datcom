def calculate_subryw(data: Dict[str, object]) -> Dict[str, object]:
    """Translate SUBRYW: the wing's subsonic CL-p, CN-p, CY-p and CN-r.

    Args:
        data: As :func:`calculate_subhyw` for the wing (``WINGD``,
            ``WINGI`` with word 11 the twist, ``WING``, ``/POWR/``), with
            ``wgpl`` in place of ``htpl``, ``syna`` words 3 (``ZW``) and 5,
            ``a`` also carrying 16 (``MACOE``) and 67 (``COS`` of the
            quarter-chord sweep), ``dyn`` word 21 (``DCMDCL``) and
            ``cbarr``.

    Returns:
        ``dyn`` and ``wing`` as left, and ``returned_early``.

    Notes:
        Kept as executed: whether the zero-lift CN-p/CL term is formed is
        decided by ``CL(NALPHA+1)``, the word after the lift curve (the
        test sits after the loop that set its index); and at a zero lift
        coefficient ``K`` is 1 with its three slopes left as they stood.
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    syna = {int(k): float(v) for k, v in data['syna'].items()}
    wing = {int(k): float(v) for k, v in data['wing'].items()}
    r = calculate_subhyw(dict(data, htpl=data['wgpl'], ht=wing,
                              syna={5: syna[5], 7: syna[3]}))
    dyn, wing = r['dyn'], r['ht']
    out = {'dyn': dyn, 'wing': wing, 'returned_early': r['returned_early'],
           'state': r['state']}
    if r['returned_early']:
        return out
    htin = {int(k): float(v) for k, v in data['htin'].items()}
    stb = {int(k): float(v) for k, v in data['stb'].items()}
    nalpha = int(data['nalpha'])
    alpha = [float(v) for v in data['alpha'][:nalpha]]
    sr, blref, im = float(data['sr']), float(data['blref']), int(data['im'])
    mach, cbarr = float(data['mach']), float(data['cbarr'])
    sspn, beta, astrw = htin[4], a[197], a[120]
    coslo4, tanco4, lamco4, lamda = a[67], a[68], a[64], a[27]
    k = beta * htin[im + 20] * RAD / (2. * _PI)
    srsw = sr / a[4]
    aaaa = 4. * sspn ** 2 / (RAD * srsw * blref ** 2)
    cl = [wing[20 + j] for j in range(1, nalpha + 1)]
    cd = [wing[j] for j in range(1, nalpha + 1)]
    alsd, cdo = dyn[44], dyn[94]
    xbocb = -dyn[21] * cbarr / a[16]
    singeg = math.sin(stb[122] / RAD)
    zee = dyn[67]
    almalo = [alpha[i] - alsd for i in range(nalpha)]
    dyn[93] = bee = math.sqrt(1. - mach ** 2 * coslo4 ** 2)
    cccc = (astrw + 4. * coslo4) / (astrw * bee + 4. * coslo4)
    dddd = astrw * bee + .5 * (astrw * bee + coslo4) * tanco4 ** 2
    eeee = astrw + .5 * (astrw + coslo4) * tanco4 ** 2
    # CL(I) with I left at NALPHA+1 by the loop before.
    if wing[21 + nalpha] != 0.0:
        dyn[92] = -(astrw + 6. * (astrw + coslo4) *
                    (xbocb * tanco4 / astrw + tanco4 ** 2 / 12.)) /             ((astrw + 4. * coslo4) * 6.)
        dyn[46] = cccc * dddd * dyn[92] / eeee
    else:
        dyn[46] = 0.
    cltan = [cl[i] * srsw * math.tan(almalo[i] / RAD) for i in range(nalpha)]
    cdcdo = [(cd[i] - cdo) * srsw for i in range(nalpha)]
    cl2paw = [(cl[i] * srsw) ** 2 / (astrw * _PI) for i in range(nalpha)]
    dyn[95] = tlip2x(_RB_X12312, _RB_X22312, _RB_Y12312, lamda, astrw,
                     2, 1, 2, 1, shape=[6])
    cnp = dyn[95] * htin[11]
    ffff = aaaa * blref / (2. * sspn)
    for i in range(1, nalpha + 1):
        clptan = wing[280 + i] * math.tan(almalo[i - 1] / RAD)
        if cl[i - 1] == 0.0:
            dyn[155 + i] = 1.
        else:
            q = alpha[i - 1]
            dyn[95 + i] = tbfunx(alpha, cltan, q, 1, 1, ordered=False)[1]
            dyn[115 + i] = tbfunx(alpha, cdcdo, q, 1, 1, ordered=False)[1]
            dyn[135 + i] = tbfunx(alpha, cl2paw, q, 1, 1, ordered=False)[1]
            dyn[155 + i] = ((dyn[95 + i] - dyn[115 + i]) /
                            (dyn[95 + i] - dyn[135 + i]))
        kay = dyn[155 + i]
        wing[320 + i] = ((kay - 1.) * clptan +
                         (kay * (dyn[46] * cl[i - 1] * srsw) + cnp) * aaaa)
    dyn[176] = dyn[71] * k / beta
    dyn[177] = (3. * singeg * (1. - 2. * zee * singeg / sspn)) * dyn[176]
    dyn[178] = float(interx(1, _RB_X1219A, [astrw], [10], _RB_Y1219A,
                            lind=10, lx1l=1))
    dyn[179] = tlip2x(_RB_X1219B, _RB_X2219B, _RB_Y1219B, lamco4, dyn[178],
                      1, 1, 1, 1, shape=[8])
    cypclo = tlip2x(_RB_X1219C, _RB_X2219C, _RB_Y1219C, lamda, dyn[179],
                    0, 0, 1, 1, shape=[3])
    aabb = astrw + 4. * coslo4
    bbcc = astrw * bee + 4. * coslo4
    ccdd = astrw * bee + coslo4
    ddee = astrw + coslo4
    dyn[180] = aabb * ccdd * cypclo / (bbcc * ddee)
    ffpg = ffff * dyn[177]
    for i in range(1, nalpha + 1):
        wing[300 + i] = ffpg + ffff * dyn[180] * srsw * dyn[155 + i] *             cl[i - 1]
    dyn[181] = tlip3x(_RB_X11336, _RB_X21336, _RB_X31336, _RB_Y71336,
                      lamco4, astrw, xbocb, 0, 1, 0, 2, 1, 1)
    dyn[182] = tlip2x(_RB_X1133A, _RB_X2133A, _RB_Y7133A, lamda, dyn[181],
                      0, 1, 0, 1, shape=[2])
    dyn[183] = tlip3x(_RB_X11337, _RB_X21337, _RB_X31337, _RB_Y71337,
                      abs(lamco4), astrw, xbocb, 0, 1, 0, 2, 1, 1)
    for i in range(1, nalpha + 1):
        dyn[183 + i] = cd[i - 1] * srsw - cl2paw[i - 1]
        wing[340 + i] = aaaa * ((dyn[182] * (cl[i - 1] * srsw) ** 2) +
                                dyn[183] * dyn[183 + i])
    return out


def calculate_supryw(data: Dict[str, object]) -> Dict[str, object]:
    """Translate SUPRYW: the wing's supersonic CL-p, CY-p and CN-p (see
    :func:`calculate_suphyw`)."""
    return calculate_suphyw(data, wing=True)
