def calculate_suphyw(data: Dict[str, object],
                     wing: bool = False) -> Dict[str, object]:
    """Translate SUPHYW: the horizontal tail's supersonic CL-p, CY-p and
    CN-p.

    Args:
        data: By name: ``mach`` (``FLC(IM+2)``), ``alpha`` (the angles of
            attack), ``nalpha``, ``sr``, ``blref``, ``htpl``, ``bo``, and
            the tail's blocks as 1-based ``{word: value}`` maps: ``a``
            (``/HTDATA/`` 4, 58, 62, 74, 118, 120), ``htin`` (3, 4, 6),
            ``slg`` (the tail's ``/SUPWH/`` half: 1, 3), ``syna`` (1),
            ``dyn`` (``/BDATA/`` 301 on: words 204-213) and ``ht`` (the
            ``HT`` result words 281, 301-340).
        state: ``intep3`` (INTEP3's saved chart pair).

    Returns:
        The ``dyn`` and ``ht`` blocks as left, and ``returned_early``.

    With ``wing`` this is SUPRYW: the same computation on the wing's blocks
    (``WINGD``, ``WINGI``, ``/POWR/``, ``/SUPWH/`` 1-141, ``WING``), gated
    on ``wgpl`` in place of ``htpl``, and with CL-p not divided by 4.

    Notes:
        Kept as executed: with a subsonic leading edge the scaled CN-p is
        formed into a mistyped local (``CNAPE``) and the word used,
        ``CNPAE`` (``DYN(212)``), is never set; ``XCG`` and ``XW`` both
        name ``SYNA(1)``, so the roll-rate side-force arm is zero; and the
        CN-p charts for a taper ratio of 0 are a dummy that reads 0.
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    htin = {int(k): float(v) for k, v in data['htin'].items()}
    slg = {int(k): float(v) for k, v in data['slg'].items()}
    dyn = {int(k): float(v) for k, v in data['dyn'].items()}
    ht = {int(k): float(v) for k, v in data['ht'].items()}
    syna = {int(k): float(v) for k, v in data['syna'].items()}
    st = data.get('state', {})
    out = {'dyn': dyn, 'ht': ht, 'returned_early': True, 'state': st}
    mach, sr, blref = (float(data[k]) for k in ('mach', 'sr', 'blref'))
    alpha = [float(v) for v in data['alpha']]
    nalpha = int(data['nalpha'])
    tanle, lamda, aw = a[62], a[118], a[120]
    sw, sspne, sspn, cr = a[4], htin[3], htin[4], htin[6]
    beta = slg[1]
    cotle = 1. / tanle
    plan = data['wgpl'] if wing else data['htpl']
    if not (plan and not data['bo']):
        if (sspn - sspne) / sspn > 0.3:
            return out
    astan2 = aw * a[74]
    baw = beta * aw
    ist = st.setdefault('intep3', {})
    clpa = intep3(astan2, baw, lamda, _CLP_CHARTS, ist)
    save = 4. * sw * sspn ** 2 / (RAD * sr * blref ** 2)
    ht[281] = clpa * slg[3] * save * aw
    if not wing:
        ht[281] = ht[281] / 4.
    dyn[204] = tlip2x(_X1110A, _X2110A, _Y2110A, a[58], mach, 2, 1, 2, 1,
                      shape=[14])
    dyn[205] = tlip2x(_X1110B, _X2110B, _Y2110B, baw, dyn[204], 2, 1, 2, 1,
                      shape=[7])
    dyn[205] = -dyn[205]
    dyn[206] = tlip2x(_X1110C, _X2110C, _Y2110C, lamda, dyn[205], 1, 1, 2,
                      1, shape=[5])
    temp = dyn[206] * sw * sspn / (sr * blref * 1641.645)
    for angle_slot in range(1, nalpha + 1):
        ht[300 + angle_slot] = temp * alpha[angle_slot - 1]
    bcotle = beta * cotle
    xcg = xw = syna[1]
    if bcotle < 1.:
        dyn[207] = intep3(baw, bcotle, lamda, _CNP_SUBSONIC, ist)
        dyn[208] = dyn[207] * tanle
        cnpaas = float(interx(1, _X12316, [bcotle], [9], _Y12316, lind=9,
                              lx1l=1, lx1u=1))
        dyn[209] = cnpaas * aw
        dyn[210] = cnpaas * aw * tanle ** 2
        dyn[211] = dyn[208] + dyn[209] + dyn[210]
        # The source forms this into CNAPE and uses CNPAE (DYN(212)).
        _cnape = save * (dyn[211] + dyn[206] * (xcg - xw) / cr * aw *
                         (1. + lamda))
        for angle_slot in range(1, nalpha + 1):
            ht[320 + angle_slot] = ((dyn[212] - ht[281])
                                    * alpha[angle_slot - 1] / RAD)
    else:
        dyn[213] = intep3(baw, bcotle, lamda, _CNP_SUPERSONIC, ist)
        aaaaa = beta * dyn[213]
        bbbbb = 2. * xcg / (blref * aw * (1. + lamda)) - .5 * tanle
        ccccc = (aaaaa + bbbbb * dyn[206] * blref / (2. * sspn)) * save
        for angle_slot in range(1, nalpha + 1):
            ht[320 + angle_slot] = ((ccccc - ht[281])
                                    * alpha[angle_slot - 1] / RAD)
    out['returned_early'] = False
    return out


