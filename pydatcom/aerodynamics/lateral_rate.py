def calculate_subhyw(data: Dict[str, object]) -> Dict[str, object]:
    """Translate SUBHYW: the horizontal tail's subsonic roll damping CL-p.

    Args:
        data: By name: ``mach``, ``alpha`` (the angles of attack),
            ``nalpha``, ``sr``, ``blref``, ``htpl``, ``bo``, ``im`` (the
            Mach index), and the tail's blocks as 1-based ``{word: value}``
            maps: ``a`` (``/HTDATA/`` 4, 27, 64, 68, 120 and ``B(2)`` as
            word 197), ``htin`` (3, 4 and ``IM+20``), ``syna`` (5, 7),
            ``stb`` (122, the tail's ``STB`` block), ``dyn`` (``/BDATA/``
            301 on) and ``ht`` (the ``HT`` result words: ``CD`` 1-20,
            ``CL`` 21-40, ``CLP`` 281-300).
        state: ``intep3``.

    Returns:
        ``dyn`` and ``ht`` as left, and ``returned_early``.

    Notes:
        Of the roll-, yaw- and yaw-rate derivatives the routine declares
        charts for, only CL-p is formed; the zero-lift angle and drag are
        read off the lift curve by TBFUNX, the curve extended by the
        zero-lift point when it does not straddle zero lift.
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    htin = {int(k): float(v) for k, v in data['htin'].items()}
    syna = {int(k): float(v) for k, v in data['syna'].items()}
    stb = {int(k): float(v) for k, v in data['stb'].items()}
    dyn = {int(k): float(v) for k, v in data['dyn'].items()}
    ht = {int(k): float(v) for k, v in data['ht'].items()}
    st = data.get('state', {})
    out = {'dyn': dyn, 'ht': ht, 'returned_early': True, 'state': st}
    nalpha = int(data['nalpha'])
    alpha = [float(v) for v in data['alpha'][:nalpha]]
    sr, blref, im = float(data['sr']), float(data['blref']), int(data['im'])
    sspne, sspn = htin[3], htin[4]
    beta = a[197]
    if not (data['htpl'] and not data['bo']):
        if (sspn - sspne) / sspn > 0.3:
            return out
    k = beta * htin[im + 20] * RAD / (2. * _PI)
    cl = [ht[20 + angle_slot] for angle_slot in range(1, nalpha + 1)]
    cd = [ht[angle_slot] for angle_slot in range(1, nalpha + 1)]
    dyn[44] = tbfunx(cl, alpha, 0., 1, 1, ordered=False)[0]
    dyn[94] = tbfunx(cl, cd, 0., 2, 2, ordered=False)[0]
    if cl[0] <= 0. and cl[-1] >= 0.:
        dyn[45] = tbfunx(alpha, cl, dyn[44], 1, 1, ordered=False)[1]
    elif cl[0] < 0.:
        dyn[45] = tbfunx(alpha + [dyn[44]], cl + [0.], dyn[44], 1, 1,
                         ordered=False)[1]
    else:
        dyn[45] = tbfunx([dyn[44]] + alpha, [0.] + cl, dyn[44], 1, 1,
                         ordered=False)[1]
    for angle_slot in range(1, nalpha + 1):
        dyn[46 + angle_slot] = tbfunx(alpha, cl, alpha[angle_slot - 1], 0, 0,
                                      ordered=False)[1]
    dyn[67] = syna[7] - syna[5]
    singeg = math.sin(stb[122] / RAD)
    dyn[68] = (1. - 2. * dyn[67] * singeg / sspn +
               3. * (dyn[67] / sspn) ** 2 * singeg ** 2)
    lamb = RAD * math.atan(a[68] / beta)
    dyn[69] = tlip2x(_HB_X12224, _HB_X22224, _HB_Y12224, a[64], a[120],
                     1, 1, 1, 1, shape=[8])
    srsw = sr / a[4]
    aaaa = 4. * sspn ** 2 / (RAD * srsw * blref ** 2)
    dyn[70] = beta * a[120] / k
    dyn[71] = intep3(dyn[70], lamb, a[27], _CLP_SUBSONIC,
                     st.setdefault('intep3', {}))
    bbbb = aaaa * dyn[71] * k * dyn[68] / (beta * dyn[45])
    for angle_slot in range(1, nalpha + 1):
        clt = cl[angle_slot - 1] * srsw
        dyn[71 + angle_slot] = dyn[69] * clt ** 2 - dyn[94] / 8. * srsw
        ht[280 + angle_slot] = bbbb * dyn[46 + angle_slot] + aaaa * dyn[71 + angle_slot]
    out['returned_early'] = False
    return out


