def calculate_supcmq(data: Dict[str, object],
                     tail: bool = False) -> Dict[str, object]:
    """Translate SUPCMQ (or, with ``tail``, SUPHMQ): Cm-q for a
    straight-tapered surface, supersonic, and transonic by blending the
    Mach 1.2 value.

    Args:
        data: By name: ``straight`` (``WINGIN(15)`` is ``STRA``),
            ``transn``, ``mach`` (``FLC(IM+2)``), ``sr``, ``cbarr``, and
            the surface's blocks as 1-based ``{word: value}`` maps: ``a``
            (3, 7, 10, 16, 27, 29, 50, 62, 67, 68, 173), ``wingin`` (69),
            ``slg`` (7, 134, 135), ``dyn`` (1, 2, 9-11, 14, 15, 17-20),
            ``tra`` (the transonic words 6, 12, 16-25, 105) and ``result``
            (101 ``CLA``, 201 ``CLQ``, 221 ``CMQ``).

    Returns:
        The blocks as left, and ``returned_early``.

    Notes:
        Kept as executed: a zero leading-edge tangent is set to 1E-5 and
        restored only on the transonic path; a taper ratio above 0.75 on a
        subsonic leading edge returns before ``CMQ`` is formed; and the
        taper ratio is left at 0.25 after a blend.
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    wingin = {int(k): float(v) for k, v in data['wingin'].items()}
    slg = {int(k): float(v) for k, v in data['slg'].items()}
    dyn = {int(k): float(v) for k, v in data['dyn'].items()}
    tra = {int(k): float(v) for k, v in data['tra'].items()}
    result = {int(k): float(v) for k, v in data['result'].items()}
    sr, cbarr = float(data['sr']), float(data['cbarr'])
    transn = bool(data['transn'])
    out = {'a': a, 'wingin': wingin, 'slg': slg, 'dyn': dyn, 'tra': tra,
           'result': result, 'returned_early': True}
    if not data['straight']:
        return out
    if a[62] == 0.:
        a[62] = .00001
    cotle = 1. / a[62]
    macoe, astrw = a[16], a[7]
    if transn:
        mach, beta = 1.2, 0.663325
        xaccr = tra[105]
        dcmdcl = (a[173] - xaccr * a[10]) / cbarr
        cna1 = tbfunx([tra[16 + table_slot] for table_slot in range(5)],
                      [tra[21 + table_slot] for table_slot in range(5)],
                      mach)[0]
    else:
        mach = float(data['mach'])
        beta = math.sqrt(mach ** 2 - 1.)
        cna1, xaccr, dcmdcl = slg[7], slg[134], slg[135]
    save = macoe * a[3] / (cbarr * sr)
    en = 1. - 4. * cotle / astrw
    dee = .66667 * a[29]
    bcotle = beta * cotle
    dyn[14] = xaccr * a[10] / cbarr
    ba = beta * astrw

    def zero_taper():
        dyn[17] = _ix1(_MQ_X2A128, _MQ_Y1A128, en, 1, 1)
        dyn[17] = (1. - en) * dyn[17]
        dyn[18] = _ix1(_MQ_X2B128, _MQ_Y1B128, en, 1, 1)
        dyn[19] = 1. - en
        aaa = -.01028 * astrw
        bbb = dyn[10] * dyn[18]
        ccc = 5.3333 * dyn[9] * (dyn[17] / dyn[19])
        ddd = -(dee - xaccr * a[10]) / cbarr
        dyn[20] = aaa * (bbb + ccc) + ddd * dyn[11] + \
            2. * ddd ** 2 * cna1 / RAD

    def packed_taper():
        bcmqpp = tlip3x(_MQ_X11129, _MQ_X21129, _MQ_X31129, _MQ_Y71129,
                        ba, bcotle, a[27], 1, 1, 0, 1, 1, 0)
        dyn[20] = (dyn[14] * dyn[15] - bcmqpp * macoe / cbarr) * save / \
            (beta * RAD)

    if bcotle >= 1.:
        acotbc = RAD * math.atan(1. / bcotle)
        bcmqp = tlip3x(_MQ_X11210, _MQ_X21210, _MQ_X31210, _MQ_Y11210,
                       ba, acotbc, a[27], 1, 1, 0, 2, 1, 0)
        dyn[20] = -(bcmqp / (RAD * beta)) * save * macoe / cbarr
    elif a[27] == 0.:
        zero_taper()
    elif a[27] < 0.25:
        qlamda = a[27]
        a[27] = 0.
        zero_taper()
        cmqp1 = dyn[20]
        a[27] = .25
        packed_taper()
        dyn[20] = (dyn[20] - cmqp1) * 4. * qlamda + cmqp1
    elif a[27] > 0.75:
        return out
    else:
        packed_taper()
    result[221] = dyn[20] + dcmdcl * result[201]
    out['returned_early'] = False
    if not transn:
        return out
    cmq12 = result[221]
    clam, clamfb = result[101], tra[12]
    if tail or float(data['mach']) > tra[6]:
        result[221] = (clam - clamfb) / (cna1 - clamfb) * \
            (cmq12 - dyn[1]) + dyn[1]
    else:
        bee = math.sqrt(1 - .36 * a[67] ** 2)
        top = a[7] ** 3 * a[68] ** 2
        compf = ((top / (a[7] * bee + 6. * a[67]) + 3. / bee) /
                 (top / (a[7] + 6. * a[67]) + 3.))
        cmq6 = compf * dyn[2]
        temp1 = 2. * PI * a[7] * DR
        temp2 = (a[7] * DR * 2. * PI / wingin[69]) ** 2
        cla6 = (temp1 / (2. + math.sqrt(temp2 * (1. + a[50] ** 2 / .8) +
                                        4.))) * a[3] / sr
        result[221] = (clam - clamfb) / (cla6 - clamfb) * \
            (cmq6 - dyn[1]) + dyn[1]
    if a[62] == .00001:
        a[62] = 0.
    return out


