def _ix1(x, y, q, l1, u1):
    return float(interx(1, x, [float(q)], [len(x)], y, lind=len(x),
                        lx1l=l1, lx1u=u1))


def calculate_supcld(data: Dict[str, object]) -> Dict[str, object]:
    """Translate SUPCLD (or SUPHLD): supersonic CL-alpha-dot.

    Args:
        data: By name: ``mach`` (``FLC(IM+2)``), ``sr``, ``cbarr``, and the
            surface's blocks as 1-based ``{word: value}`` maps: ``a``
            (words 3, 7, 9, 10, 16, 27, 29, 58, 62), ``wingin`` (1, 3, 4),
            ``slg`` (1 ``BETA``, 134 ``XACCR``), ``dyn`` (9 ``EPPBC``,
            10 ``GBC`` and the words CALCA and this routine set) and
            ``result`` (word 241, ``CLADWH``).

    Returns:
        The four blocks as left.

    Notes:
        Kept as executed: a taper ratio between 0 and 0.25 is blended from
        the zero-taper theory and CALCA at 0.25, and the taper ratio
        ``A(27)`` is left at 0.25 afterwards.
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    wingin = {int(k): float(v) for k, v in data['wingin'].items()}
    slg = {int(k): float(v) for k, v in data['slg'].items()}
    dyn = {int(k): float(v) for k, v in data['dyn'].items()}
    result = {int(k): float(v) for k, v in data['result'].items()}
    mach, sr, cbarr = (float(data[k]) for k in ('mach', 'sr', 'cbarr'))
    if a[62] == 0.:
        a[62] = .00001
    cotle = 1. / a[62]
    beta = slg[1]
    bcotle = beta * cotle
    acotbc = RAD * math.atan(1. / bcotle)
    dyn[14] = slg[134] * a[10] / cbarr
    save = a[16] * a[3] / (cbarr * sr)
    ba = beta * a[7]
    en = 1. - 4. * cotle / a[7]
    qlamda = 9.

    def zero_taper():
        dyn[23] = _ix1(_X2A417, _Y1A417, en, 1, 1)
        dyn[24] = _ix1(_X2B417, _Y1B417, en, 1, 1)
        dyn[25] = _ix1(_X2C417, _Y1C417, en, 2, 2)
        dyn[25] = dyn[25] * (1. - en)
        result[241] = (-.027414 * a[7] * mach ** 2 / beta ** 2 *
                       (-3. * dyn[10] * dyn[25] + 2. * dyn[9] * dyn[24] +
                        dyn[9] * dyn[23] / mach ** 2) * save)

    def calca_taper():
        out = calculate_calca(mach, a, wingin)
        if out is not None:
            dyn.update(out['dyn'])
        result[241] = save / (RAD * beta ** 2) * (mach ** 2 * dyn[22] -
                                                  dyn[16])

    if bcotle >= 1.:
        bclad1 = tlip3x(_X14111, _X24111, _X34111, _Y14111, ba, acotbc,
                        a[27], 2, 1, 0, 1, 1, 0)
        bclad2 = tlip3x(_X1A111, _X2A111, _X3A111, _Y1A111, ba, acotbc,
                        a[27], 2, 1, 0, 2, 1, 0)
        result[241] = save / (RAD * beta ** 3) * (mach ** 2 * bclad1 -
                                                  bclad2)
    elif a[27] == 0.:
        zero_taper()
    elif a[27] >= 0.25:
        calca_taper()
    else:
        qlamda = a[27]
        a[27] = 0.
        zero_taper()
        cld1 = result[241]
        a[27] = .25
        calca_taper()
        result[241] = (result[241] - cld1) * 4. * qlamda + cld1
    if a[62] == .00001:
        a[62] = 0.
    return {'a': a, 'wingin': wingin, 'slg': slg, 'dyn': dyn,
            'result': result}


