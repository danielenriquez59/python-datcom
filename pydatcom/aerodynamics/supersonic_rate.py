def calculate_supcmd(data: Dict[str, object]) -> Dict[str, object]:
    """Translate SUPCMD (or SUPHMD): supersonic Cm-alpha-dot.

    Args:
        data: As :func:`calculate_supcld`, with ``a`` also carrying word
            173 (``DXCG``), ``dyn`` the F-functions 17-19 and CALCA's
            words 26 and 27, and ``result`` words 241 (``CLADWH``) and 261
            (``CMADWH``).

    Returns:
        The blocks as left.

    Notes:
        Kept as executed: for a taper ratio between 0 and 0.25 the blend
        starts from the result word ``CMADWH`` as it stood rather than the
        zero-taper value just formed, and weights by the taper ratio after
        it has been reset to 0.25, so it returns the 0.25 value; the taper
        ratio is left at 0.25.  (SUPCLD, run first, has usually set it to
        0.25 already.)
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    slg = {int(k): float(v) for k, v in data['slg'].items()}
    dyn = {int(k): float(v) for k, v in data['dyn'].items()}
    result = {int(k): float(v) for k, v in data['result'].items()}
    mach, sr, cbarr = (float(data[k]) for k in ('mach', 'sr', 'cbarr'))
    if a[62] == 0.:
        a[62] = .00001
    cotle = 1. / a[62]
    beta = slg[1]
    bcotle = beta * cotle
    acotbc = RAD * math.atan(1. / bcotle)
    dyn[14] = slg[134] * a[10] / cbarr
    save = a[16] * a[3] / (cbarr * sr)
    ba = beta * a[7]
    dee = .66667 * a[29]
    en = 1. - 4. * cotle / a[7]
    macoe, astrw = a[16], a[7]

    def zero_taper():
        dyn[8] = _ix1(_MD_X2A429, _MD_Y7A429, en, 1, 1)
        dyn[5] = _ix1(_MD_X2B429, _MD_Y7B429, en, 1, 1)
        xx = (-.010281 * astrw * mach ** 2 / beta ** 2 * save * macoe /
              cbarr)
        yy = dyn[10] * dyn[18] + 5.3333 * dyn[9] * dyn[17] / dyn[19]
        zz = save * macoe / (cbarr * RAD)
        ww = (1.77778 * astrw * mach ** 2 * dyn[9] * dyn[5] / beta ** 2 +
              .19635 * astrw * dyn[9] * dyn[8] / beta ** 2)
        dyn[7] = xx * yy + zz * ww - (dee * result[241]) / cbarr

    def calca_taper():
        dyn[7] = (save * macoe / (beta ** 2 * cbarr * RAD) *
                  (mach ** 2 * dyn[26] - dyn[27]))

    if bcotle >= 1.:
        b1 = tlip3x(_MD_X14213, _MD_X24213, _MD_X34213, _MD_Y14213, ba,
                    acotbc, a[27], 1, 1, 0, 2, 1, 0)
        b2 = tlip3x(_MD_X1A213, _MD_X2A213, _MD_X3A213, _MD_Y1A213, ba,
                    acotbc, a[27], 1, 1, 0, 2, 1, 0)
        dyn[7] = save * macoe / (cbarr * RAD) * (
            mach ** 2 / beta ** 3 * b1 + (mach ** 2 / beta ** 2 + 1.) *
            b2 / beta)
    elif a[27] == 0.:
        zero_taper()
    elif a[27] >= 0.25:
        calca_taper()
    else:
        a[27] = 0.
        zero_taper()
        cmdd1 = result[261]
        a[27] = .25
        calca_taper()
        dyn[7] = (dyn[7] - cmdd1) * 4. * a[27] + cmdd1
    result[261] = dyn[7] + a[173] * result[241] / cbarr
    if a[62] == .00001:
        a[62] = 0.
    return {'a': a, 'slg': slg, 'dyn': dyn, 'result': result}


