def calculate_suppaw(data: Dict[str, object]) -> Dict[str, object]:
    """Translate SUPPAW (or SUPPAH): supersonic CL-q.

    Args:
        data: By name: ``straight`` (``WINGIN(15)`` is ``STRA``),
            ``transn``, ``sr``, ``cbarr``, and the surface's blocks as
            1-based ``{word: value}`` maps: ``a`` (3, 7, 10, 16, 27, 29,
            62), ``slg`` (1 ``BETA``, 7, 134, 135), ``dyn`` (9-15) and
            ``result`` (201 ``CLQ``).

    Returns:
        The blocks as left, and ``returned_early``.

    Notes:
        Kept as executed: the supersonic leading-edge chart (Figure
        7.1.1.1-11, drawn against the Mach-cone angle in degrees) is read
        at ``BETA*COT(LE)``; transonic runs write the Mach 1.2 ``BETA``
        into ``SLG(1)``; a surface that is not straight-tapered returns
        after the zero-taper wing factors, leaving a blend's taper ratio at
        0; and the zero leading-edge tangent is restored only when ``CLQ``
        is formed.
    """
    a = {int(k): float(v) for k, v in data['a'].items()}
    slg = {int(k): float(v) for k, v in data['slg'].items()}
    dyn = {int(k): float(v) for k, v in data['dyn'].items()}
    result = {int(k): float(v) for k, v in data['result'].items()}
    sr, cbarr = float(data['sr']), float(data['cbarr'])
    transn = bool(data['transn'])
    out = {'a': a, 'slg': slg, 'dyn': dyn, 'result': result,
           'returned_early': True}
    if a[62] == 0.:
        a[62] = .00001
    if transn:
        slg[1] = math.sqrt(1.2 ** 2 - 1.)
    beta = slg[1]
    cotle = 1. / a[62]
    bcotle = beta * cotle
    dyn[14] = slg[134] * a[10] / cbarr
    save = a[16] * a[3] / (cbarr * sr)
    ba = beta * a[7]
    cna1 = slg[7]

    def zero_taper():
        """Label 1000; False when the surface is not straight-tapered."""
        dyn[9] = tlip2x(_QW_X11118, _QW_X21118, _QW_Y71118, 1., bcotle,
                        0, 0, 0, 2, shape=[2])
        dyn[10] = tlip2x(_QW_X11118, _QW_X21118, _QW_Y71118, 2., bcotle,
                         0, 0, 0, 2, shape=[2])
        if not data['straight']:
            return False
        en = 1. - 4. * cotle / a[7]
        f3n = tlip1x(_QW_X2A119, _QW_Y7A119, en, 1, 1)
        f4n = _ix1(_QW_X2B119, _QW_Y7B119, en, 1, 1)
        dyn[13] = f4n / (1. - en)
        dyn[12] = f3n * (1. - en)
        dee = .66667 * a[29]
        dyn[11] = (.027414 * a[7] * (3. * dyn[10] * dyn[12] -
                                     2. * dyn[9] * dyn[13]) * save +
                   2. * (dee - slg[134] * a[10]) * cna1 / (cbarr * RAD))
        return True

    def packed_taper():
        dyn[15] = tlip3x(_QW_X11110, _QW_X21110, _QW_X31110, _QW_Y11110,
                         ba, bcotle, a[27], 1, 0, 0, 2, 0, 0)
        clqpp = dyn[15] / beta
        dyn[11] = (clqpp * save - 2. * dyn[14] * cna1) / RAD

    if bcotle > 1.:
        bclqpp = tlip3x(_QW_X11111, _QW_X21111, _QW_X31111, _QW_Y11111,
                        ba, bcotle, a[27], 1, 0, 0, 2, 1, 0)
        dyn[11] = bclqpp * save / (beta * RAD)
    elif a[27] == 0.:
        if not zero_taper():
            return out
    elif a[27] >= 0.25:
        packed_taper()
    else:
        qlamda = a[27]
        a[27] = 0.
        if not zero_taper():
            return out
        clqpw1 = dyn[11]
        a[27] = .25
        packed_taper()
        dyn[11] = ((dyn[11] - clqpw1) / .25) * qlamda + clqpw1
        a[27] = qlamda
    if transn:
        return out
    result[201] = dyn[11] - 2. * slg[135] * cna1 / RAD
    out['returned_early'] = False
    if a[62] == .00001:
        a[62] = 0.
    return out
